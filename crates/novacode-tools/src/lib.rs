/// What a tool returns. `details` is UI-only and never sent to a model.
#[derive(Debug, Clone, PartialEq)]
pub struct ToolOutput {
    pub content: Vec<Block>,
    pub is_error: bool,
    pub details: Option<Value>,
}

impl ToolOutput {
    pub fn text(t: impl Into<String>) -> Self {
        Self {
            content: vec![Block::text(t)],
            is_error: false,
            details: None,
        }
    }
    pub fn error(t: impl Into<String>) -> Self {
        Self {
            content: vec![Block::text(t)],
            is_error: true,
            details: None,
        }
    }
}

/// How a tool reaches the model (L5.16). Each tool declares its default; settings
/// (`tools.<name>.exposure`) override it (L4.8).
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Exposure {
    /// Declared to the model.
    Listed,
    /// Callable only from codemode scripts (L7.5).
    CodemodeOnly,
    /// Found through `tool_search` (L5.17).
    Deferred,
    /// Only the user and the UI use it.
    Hidden,
}

/// The tools the model may call directly. The rest stay out of the request, so
/// their declarations cost no tokens.
// shortcut: non-listed tools are dropped; keep them for codemode/tool_search when those land (M9, M10).
pub fn listed(tools: Vec<Arc<dyn Tool>>, overrides: impl Fn(&str) -> Option<Exposure>) -> Vec<Arc<dyn Tool>> {
    tools
        .into_iter()
        .filter(|t| overrides(t.name()).unwrap_or(t.exposure()) == Exposure::Listed)
        .collect()
}

/// Which end of a long output to keep (L5.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Keep {
    Head,
    Tail,
}

/// Per-call context handed to [`Tool::execute`].
#[derive(Clone)]
pub struct ToolCtx {
    pub cwd: PathBuf,
    pub env: Arc<dyn ExecutionEnv>,
    pub cancel: CancellationToken,
    /// Progress text for the UI (bash output). Sends never block.
    pub updates: Option<mpsc::Sender<String>>,
    pub files: Arc<FileState>,
    pub session_id: String,
    /// The session's process manager (L5.11); bash hands timed-out commands to it.
    pub processes: Option<Arc<process::ProcessManager>>,
}

impl ToolCtx {
    /// Resolve a model-supplied path against the cwd, expanding `~`.
    pub fn path(&self, p: &str) -> PathBuf {
        let p = p.trim();
        if let Some(rest) = p.strip_prefix("~/")
            && let Some(home) = std::env::var_os("HOME")
        {
            return Path::new(&home).join(rest);
        }
        self.cwd.join(p)
    }

    pub fn update(&self, text: String) {
        if let Some(tx) = &self.updates {
            let _ = tx.try_send(text); // a slow UI drops progress, never blocks the tool
        }
    }
}

/// One tool (L5.1). Rendering belongs to the UI.
pub trait Tool: Send + Sync {
    fn name(&self) -> &str;
    fn description(&self) -> &str;
    /// JSON schema of the arguments, fixed key order.
    fn schema(&self) -> Value;
    /// Run alone: a batch containing this tool runs sequentially (L3.3).
    fn sequential(&self) -> bool {
        false
    }
    /// Can produce large output; gets `accept_large_output` (L5.3).
    fn large_output(&self) -> bool {
        true
    }
    fn keep(&self) -> Keep {
        Keep::Head
    }
    /// Default exposure (L5.16); settings can override it.
    fn exposure(&self) -> Exposure {
        Exposure::Listed
    }
    /// Lines for the prompt's `tool_guidelines` section, sent only while this tool is listed.
    fn guidelines(&self) -> &[&str] {
        &[]
    }
    fn execute<'a>(&'a self, args: Value, ctx: &'a ToolCtx) -> BoxFuture<'a, ToolOutput>;

    fn def(&self) -> ToolDef {
        ToolDef {
            name: self.name().into(),
            description: self.description().into(),
            schema: self.schema(),
        }
    }
}

/// Schema for typed args, generated by schemars and stripped of noise the model doesn't need.
/// The guidelines of these tools in tool order, each line once.
pub fn guidelines(tools: &[Arc<dyn Tool>]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for g in tools.iter().flat_map(|t| t.guidelines()) {
        if !out.iter().any(|o| o == g) {
            out.push((*g).to_string());
        }
    }
    out
}

pub fn schema_for<T: schemars::JsonSchema>() -> Value {
    let mut v = serde_json::to_value(schemars::schema_for!(T)).unwrap_or_default();
    if let Some(o) = v.as_object_mut() {
        o.remove("$schema");
        o.remove("title");
    }
    v
}

/// Parse typed args, turning serde errors into a model-readable error.
pub fn parse<T: DeserializeOwned>(args: Value) -> Result<T, ToolOutput> {
    serde_json::from_value(args).map_err(|e| ToolOutput::error(format!("invalid arguments: {e}")))
}

/// The default built-in set. `apply_patch` replaces `edit` for model families that use it (L5.7).
pub fn builtins(apply_patch: bool) -> Vec<Arc<dyn Tool>> {
    let edit: Arc<dyn Tool> = if apply_patch {
        Arc::new(patch::ApplyPatch)
    } else {
        Arc::new(edit::Edit)
    };
    vec![
        Arc::new(read::Read),
        Arc::new(write::Write),
        edit,
        Arc::new(bash::Bash),
        Arc::new(search::Grep),
        Arc::new(search::Find),
        Arc::new(search::Ls),
    ]
}

#[cfg(test)]
pub(crate) mod testutil {
    use super::*;

    pub fn ctx(dir: &Path) -> ToolCtx {
        ToolCtx {
            cwd: dir.to_path_buf(),
            env: Arc::new(LocalEnv),
            cancel: CancellationToken::new(),
            updates: None,
            files: Arc::new(FileState::default()),
            session_id: "test".into(),
            processes: None,
        }
    }

    pub fn text(o: &ToolOutput) -> String {
        o.content
            .iter()
            .filter_map(|b| match b {
                Block::Text { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect()
    }
}

#[cfg(test)]
mod exposure_tests {
    use super::*;

    #[test]
    fn guidelines_follow_the_tool_set() {
        let edit = guidelines(&builtins(false)).join("\n");
        assert!(edit.contains("`edit`, not with sed") && edit.contains("non-interactive"));
        assert!(!edit.contains("apply_patch"));
        let patch = guidelines(&builtins(true)).join("\n");
        assert!(patch.contains("`apply_patch`, not with sed") && !patch.contains("`edit`"));
        // Only listed tools reach the prompt: without bash, no bash guideline.
        let no_bash: Vec<_> = builtins(false).into_iter().filter(|t| t.name() != "bash").collect();
        assert!(!guidelines(&no_bash).join("").contains("non-interactive"));
    }

    #[test]
    fn settings_override_the_declared_exposure() {
        let names = |t: Vec<Arc<dyn Tool>>| t.iter().map(|t| t.name().to_string()).collect::<Vec<_>>();
        assert_eq!(
            names(listed(builtins(false), |_| None)).len(),
            7,
            "built-ins are listed by default"
        );
        let got = names(listed(builtins(false), |n| match n {
            "ls" => Some(Exposure::Hidden),
            "find" => Some(Exposure::CodemodeOnly),
            _ => None,
        }));
        assert_eq!(got, ["read", "write", "edit", "bash", "grep"]);
        let e: Exposure = serde_json::from_value(serde_json::json!("codemode-only")).unwrap();
        assert_eq!(e, Exposure::CodemodeOnly);
    }
}
